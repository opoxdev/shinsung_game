// Manual/CI Chromium smoke test: run after 'npm run build' with playwright installed.
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
  const page=await browser.newPage({viewport:{width:1280,height:800},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('file://'+path.join(root,'dist/index.html'),{waitUntil:'domcontentloaded'});
  await page.waitForSelector('[data-action="start"]',{timeout:10000});
  await page.click('[data-action="events"]');
  assert.equal(await page.locator('.achievement-card').count(),35,'all categorized achievements are visible');
  assert.equal(await page.locator('.achievement-tabs button').count(),7);
  const archiveScroll=await page.locator('.content').evaluate(el=>({height:el.clientHeight,scroll:el.scrollHeight}));
  assert.ok(archiveScroll.scroll>archiveScroll.height,'the long archive must have its own scroll area');
  await page.locator('.content').evaluate(el=>{el.scrollTop=240;});
  assert.ok((await page.locator('.content').evaluate(el=>el.scrollTop))>0,'achievements can actually scroll');

  assert.ok(await page.locator('.achievement-card[data-state="ready"]').count()===0);
  await page.click('[data-action="achievementFilter"][data-id="collection"]');
  assert.ok(await page.locator('.achievement-card').count()>=4);
  await page.click('[data-action="achievementFilter"][data-id="ready"]');
  assert.match(await page.locator('.achievement-empty').textContent(),/수령 가능한 보상/);
  await page.click('[data-action="achievementFilter"][data-id="all"]');
  await page.click('[data-action="nav"][data-id="home"]');
  await page.click('[data-action="pvp"]');
  assert.equal(await page.locator('.mm-room-grid').getAttribute('data-mode'),'pvp');
  await page.waitForSelector('.mm-error',{timeout:8000});
  await page.click('[data-action="close"]');
  await page.click('[data-action="coop"]');
  assert.equal(await page.locator('.mm-room-grid').getAttribute('data-mode'),'coop');
  await page.click('[data-action="close"]');
  await page.click('[data-action="nav"][data-id="towers"]');
  assert.equal(await page.locator('.tower-card').count(),30);
  await page.click('[data-action="nav"][data-id="shop"]');
  assert.ok(await page.locator('.shop-tabs').count());
  await page.click('[data-action="nav"][data-id="home"]');
  assert.match(await page.locator('.story-preview h3').textContent(),/작은 별의 첫걸음/);
  await page.click('[data-action="difficulty"][data-id="hard"]');
  assert.match(await page.locator('.story-preview h3').textContent(),/강철 심장의 반란/);
  await page.click('[data-action="storyGuide"]');
  assert.equal(await page.locator('.story-chapter-step.locked').count(),6,'future chapters hidden in lobby');
  await page.click('[data-action="close"]');
  await page.click('[data-action="difficulty"][data-id="easy"]');
  await page.click('[data-action="start"]');
  await page.waitForSelector('#battlefield',{timeout:10000});
  await page.waitForSelector('.story-dialogue',{timeout:10000});
  assert.match(await page.locator('.story-dialogue').textContent(),/빛을 잃은 초원/);
  assert.match(await page.locator('.story-dialogue').textContent(),/새총잡이/);
  assert.equal(await page.locator('.story-dialogue .story-speaker svg[data-design="v2"][data-base="scout"]').count(),1,
    'first speaker uses the actual in-game scout tower character');
  assert.ok((await page.locator('.story-dialogue .story-speaker svg').boundingBox()).height>50,'portrait must be visibly sized');
  await page.click('[data-action="storyNext"]');
  assert.match(await page.locator('.story-dialogue').textContent(),/고블린 소환사/);
  assert.equal(await page.locator('.story-dialogue .story-speaker svg[data-base="summoner"]').count(),1,
    'portrait switches to the real summoner tower along with the dialogue');
  await page.click('[data-action="storyDismiss"]');
  assert.equal(await page.locator('.story-overlay:visible').count(),0);
  await page.click('[data-action="storyReplay"]');
  assert.equal(await page.locator('.story-dialogue').count(),1);
  await page.click('[data-action="storyToggle"]');
  assert.equal(await page.locator('.story-dialogue').count(),0,'optional dialogue never forces an overlay');
  await page.click('[data-action="storyToggle"]');
  await page.click('[data-action="storyReplay"]');
  await page.click('[data-action="storyJournal"]');
  assert.equal(await page.locator('.story-chapter-step.unlocked').count(),1);
  assert.equal(await page.locator('.story-chapter-step.locked').count(),5);
  await page.click('[data-action="close"]');
  await page.waitForFunction(()=>document.getElementById('wave-clock')?.textContent.includes('s'));
  const first=Number((await page.locator('#wave-clock').textContent()).match(/(\d+)s/)?.[1]);
  await page.waitForTimeout(1800);
  const after=Number((await page.locator('#wave-clock').textContent()).match(/(\d+)s/)?.[1]);
  assert.ok(after<first,'Wave countdown should progress smoothly in local battle');
  const waveScale=await page.locator('#wave-progress-fill').evaluate(el=>getComputedStyle(el).transform);
  assert.notEqual(waveScale,'matrix(1, 0, 0, 1, 0, 0)','wave progress should reflect elapsed wave time');
  await page.setViewportSize({width:390,height:760});
  await page.click('[data-action="storyReplay"]');
  assert.equal(await page.locator('.story-dialogue .story-speaker svg[data-base="scout"]').count(),1);
  const portraitBounds=await page.locator('.story-dialogue .story-speaker svg').boundingBox();
  assert.ok(portraitBounds.width>=45&&portraitBounds.height>=65,'mobile tower portrait remains readable');
  const storyBounds=await page.locator('#story-overlay').boundingBox();
  assert.ok(storyBounds&&storyBounds.x>=0&&storyBounds.x+storyBounds.width<=390,'story overlay fits on mobile');
  assert.equal(await page.locator('.battle-mobile-menu:visible').count(),1,'mobile battle menu must remain accessible');
  await page.click('.battle-mobile-menu');
  await page.click('[data-action="leave"]');
  assert.match(await page.locator('.story-preview').textContent(),/기록 1 \/ 6/);
  await page.click('[data-action="storyGuide"]');
  assert.equal(await page.locator('.story-chapter-step.unlocked').count(),1,'chapter remains unlocked on return to lobby');
  await page.click('[data-action="close"]');
  assert.deepEqual(errors,[],'Uncaught browser errors: '+errors.join('; '));
  console.log('Browser smoke passed: 35 achievement cards, categories, UI filters, tower portraits, dialogue, PvP/co-op, shop and wave clock.');
}finally{await browser.close();}
